    /** 英文名（忽略大小写）→ 星体索引。 */
    private val byName: Map<String, Star> =
        stars.associateBy { it.nameEn.lowercase() }

    /** 按 id 取星。 */
    fun byId(id: Int): Star = stars[id - 1]

    /** 星座连线引用的名称解析。 */
    fun idOf(nameEn: String): Int =
        byName[nameEn.lowercase()]?.id
            ?: throw IllegalArgumentException("Unknown star name in constellation topology: $nameEn")

    fun find(nameEn: String): Star? = byName[nameEn.lowercase()]

    /** 全天最亮 N 颗（供"今夜推荐“）。 */
    fun brightest(n: Int): List<Star> = stars.sortedBy { it.mag }.take(n)

