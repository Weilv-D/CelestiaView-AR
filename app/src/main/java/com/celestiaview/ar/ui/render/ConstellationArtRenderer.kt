    private fun strokes(vararg xy: Float): Array<FloatArray> {
        val out = ArrayList<FloatArray>()
        var i = 0
        while (i + 3 < xy.size) {
            out.add(floatArrayOf(xy[i], xy[i + 1], xy[i + 2], xy[i + 3]))
            i += 4
        }
        // 相邻段首尾相接的连续路径：每 4 个数一段折线，由渲染层顺序连线
        return out.toTypedArray()
    }

    /** 查询星座线稿（无线稿的星座返回 null）。 */
    fun strokesFor(abbr: String): Array<FloatArray>? = ART[abbr]

    /** 线稿覆盖的星座数（自检用）。 */
    val size: Int get() = ART.size
